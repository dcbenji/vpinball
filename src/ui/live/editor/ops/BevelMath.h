#pragma once

#include "math/vector.h"

// Pure geometry of the bevel tool (see BevelOp): corners of a drag point outline (its control polygon) cut back along both adjacent edges.
// Lengths are in VP units, angles in radians.
namespace VPX::EditorUI::BevelMath
{

struct Result
{
   vector<Vertex2D> points;
   vector<int> source; // Index of the input point each output point comes from
   vector<bool> generated; // Whether the point was generated by a bevel (the bevelled corner itself is removed)
   vector<int> cutOf; // Index of the input corner whose cut the segment from the point to the next one belongs to, -1 for the rest of an input edge
   float minRadius = FLT_MAX; // Smallest fillet radius of the bevelled corners (FLT_MAX when none was bevelled)
};

// Replaces each corner listed in corners (indices in points) by points at width along both adjacent edges: with 1 step, a flat cut
// (2 points), with more, a round fillet of steps segments (steps + 1 points) tangent to both edges. The width is clamped per corner so that
// a cut never passes the middle of an adjacent edge (so it never overlaps the cut of a neighbouring corner). Endpoints of an open curve,
// corners within half a degree of straight (or of folded back), and corners with a zero length edge are kept.
Result Bevel(const vector<Vertex2D> &points, const vector<int> &corners, bool closed, float width, int steps);

// Per segment flags of the bevelled outline (e.g. slingshot, the flag of a point is the one of the segment to the next point), from the
// flags of the input segments: the rest of an input edge keeps its flag, a cut is flagged only if both edges of its corner were
vector<bool> SegmentFlags(const Result &bevel, const vector<bool> &flags);

// Angle at the corner between its edges to prev and next (pi for a straight line, pi/2 for a square corner)
float CornerAngle(const Vertex2D &prev, const Vertex2D &corner, const Vertex2D &next);

// Radius of the fillet of a corner of the given angle, tangent to both edges at width from the corner
float FilletRadius(float width, float cornerAngle);

}
