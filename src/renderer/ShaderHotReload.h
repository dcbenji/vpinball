#include <bgfx/bgfx.h>
#include <map>
#include <set>
#include <thread>
#include <nlohmann/json.hpp>

namespace bgfx { struct EmbeddedShader; }
class Player;
class Shader;
enum class ShaderTechnique : unsigned int;

class ShaderHotReload final
{
public:
   static ShaderHotReload* Get(); // nullptr when disabled, which is the normal case. Thread safe

   // One manifest line per shader variant ("name|source|type|defines"), generated by shaders.cmake in the bgfx_*.h headers, null terminated
   void AddManifest(const char* const* lines);
   // Shader::loadProgram: remembers what each program is built from. Create is called instead of createEmbeddedShader, so a shader recreated after a reload is the edited one
   bgfx::ShaderHandle CreateShader(const bgfx::EmbeddedShader* embedded, const char* name);
   void RegisterProgram(Shader* shader, ShaderTechnique technique, bool isClipVariant, const char* vsName, const char* fsName, const bgfx::EmbeddedShader* embedded);
   void UnregisterShader(Shader* shader);

   void Update(Player* player); // Logic thread, once per frame, between frames
   nlohmann::json Status() const; // Any thread
   uint32_t GetShadowRestartFrame() const { return m_shadowRestartFrame; } // Frame of the last swap that invalidated the shadows
   void RequestReload(const string& file); // Any thread: recompile as if edited

   ~ShaderHotReload();

private:
   struct Variant { string name, source, type, defines; };
   struct Program { Shader* shader; ShaderTechnique technique; bool isClipVariant; string vs, fs; const bgfx::EmbeddedShader* embedded; };
   using Blobs = std::map<string, std::shared_ptr<vector<uint8_t>>>;
   struct Batch
   {
      string files;
      Blobs blobs;
      uint64_t editNs = 0, detectNs = 0, compiledNs = 0, swappedNs = 0, pixelsNs = 0;
      uint32_t swapFrame = 0;
      int programs = 0;
   };

   explicit ShaderHotReload(const string& dir, const string& shaderc);
   void WatchLoop();
   void Compile(const vector<string>& changedFiles, uint64_t editNs, uint64_t detectNs);
   std::set<string> SourcesUsing(const std::set<string>& changedFiles) const;
   void Apply(const std::shared_ptr<Batch>& batch); // Render thread, end of frame, logic thread blocked
   bgfx::ShaderHandle MakeShader(const string& name, const Blobs* extra, const bgfx::EmbeddedShader* embedded) const;
   void SetError(const string& error);

   const string m_dir, m_shaderc;
   std::filesystem::path m_workDir;
   std::thread m_thread;
   std::atomic<bool> m_stop { false };
   std::atomic<uint32_t> m_shadowRestartFrame { 0 };

   mutable std::mutex m_mutex; // Everything below
   vector<Variant> m_variants;
   vector<Program> m_programs;
   vector<string> m_forced; // Files to recompile though not edited
   Blobs m_blobs; // Latest compiled blob of each edited variant
   std::shared_ptr<Batch> m_ready; // Compiled, waiting for its swap
   std::shared_ptr<Batch> m_swapped; // Swapped by the render thread, not yet seen by the logic thread
   std::shared_ptr<Batch> m_measuring; // Swapped, waiting for its first presented frame
   string m_state = "idle";
   string m_error; // Last error, cleared by the next successful reload
   bool m_errorPending = false;
   int m_generation = 0; // Successful reloads, presented
   int m_attempts = 0; // Finished reloads, successful or not
   nlohmann::json m_last;
};

#endif
